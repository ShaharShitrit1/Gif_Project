import { test } from "vitest";
import { parseChatText } from "../../lib/parser";
import { computeStats } from "../../lib/stats";
import { generateChat } from "./generate";
test("smoke stats", () => {
  const txt = generateChat(3000, 7, 120);
  const chat = parseChatText(txt);
  const s = computeStats(chat);
  const { daily, monthly, perPerson, firstMessages, lastMessages, ...rest } = s;
  console.log(JSON.stringify(rest, null, 1).slice(0, 6000));
  console.log("daily", daily.length, daily.slice(0, 3), "monthly", JSON.stringify(monthly.slice(0, 2)));
  console.log(JSON.stringify(perPerson[0], null, 0));
  console.log(perPerson.map((p) => `${p.id} ${p.name} m=${p.messages} laugh=${JSON.stringify(p.laugh)} ment=${p.mentionedByOthers} gm=${p.goodMorning} gn=${p.goodNight} st=${p.conversationStarts} end=${p.conversationEnds} mono=${p.longestMonologue} med=${p.medianReplyMs}`).join("\n"));
  const big = parseChatText(generateChat(100000, 1, 1500));
  let t = performance.now();
  computeStats(big);
  console.log("100k stats ms", performance.now() - t);
  t = performance.now();
  parseChatText(generateChat(100000, 1, 1500));
  console.log("100k parse+gen ms", performance.now() - t);
});
